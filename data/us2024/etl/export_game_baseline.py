"""
Generate packages/packs/src/us/baseline2024.ts from the verified dataset.

The game needs, per state: vote share by party, registered voters and a
turnout rate. Shares and turnout come straight from the certified data:

  share(party)  = candidate votes / FEC presidential votes total
  turnout       = FEC presidential votes total / EAVS A1a registered total
  registered    = EAVS A1a

Game-only fallbacks (never written back to the dataset, marked in the output):
  - Registered total null because a few jurisdictions are missing (HI, ME):
    use the partial sum of the reporting jurisdictions.
  - No voter registration at all (ND): registered = votes / median turnout of
    the states with complete data.

Run: python3 -I etl/export_game_baseline.py   (from data/us2024)
"""
import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "output"
TARGET = ROOT.parent.parent / "packages" / "packs" / "src" / "us" / "baseline2024.ts"

rows = list(csv.DictReader(open(OUT / "us_presidential_2024_official_51.csv")))
long_rows = list(csv.DictReader(open(OUT / "us_presidential_2024_candidates_long.csv")))
exceptions = list(csv.DictReader(open(OUT / "eavs_exceptions.csv")))
manifest = json.loads((OUT / "source_manifest.json").read_text())

cand = {}
for r in long_rows:
    cand.setdefault(r["state_abbr"], {})[r["candidate_column"]] = int(r["votes"])

partial_a1a = {e["state_abbr"]: int(e["state_partial_sum_excluding_missing"]) for e in exceptions if e["field"] == "A1a"}

complete_turnouts = [
    int(r["presidential_votes_total"]) / int(r["registered_total"]) for r in rows if r["registered_total"]
]
median_turnout = statistics.median(complete_turnouts)

records = []
for r in rows:
    s = r["state_abbr"]
    total = int(r["presidential_votes_total"])
    c = cand[s]
    dem = int(r["democratic_votes"])
    rep = int(r["republican_votes"])
    lib = c.get("OLIVER", 0)   # Libertarian nominee's column
    grn = c.get("STEIN", 0)    # Green nominee's column
    other = total - dem - rep - lib - grn
    if r["registered_total"]:
        registered, reg_note = int(r["registered_total"]), "EAVS A1a"
    elif s in partial_a1a and s != "ND":
        registered, reg_note = partial_a1a[s], "game-only: partial EAVS A1a (some jurisdictions not reported)"
    else:
        registered, reg_note = round(total / median_turnout), "game-only: no voter registration; votes / median turnout"
    records.append({
        "id": s.lower(),
        "shares": {k: round(v / total, 6) for k, v in {"dem": dem, "rep": rep, "lib": lib, "grn": grn, "other": other}.items()},
        "turnout": round(total / registered, 6),
        "registeredVoters": registered,
        "registeredSource": reg_note,
        "presidentialVotes": total,
    })

fec = manifest["sources"]["fec_xlsx"]
eavs = manifest["sources"]["eavs_zip"]
lines = [
    "// GENERATED by data/us2024/etl/export_game_baseline.py. Do not edit by hand.",
    "// Actual certified election results, 2024: starting position only. Play is fictional.",
    f"// FEC: {fec['title']} sha256 {fec['sha256']}",
    f"// EAC: {eavs['title']} sha256 {eavs['sha256']}",
    "// Shares are candidate-aligned (Harris = dem, Trump = rep, Oliver = lib, Stein = grn).",
    f"// Median turnout used for game-only fallbacks: {median_turnout:.4f}",
    "",
    "export interface UsBaselineRecord {",
    "  id: string;",
    "  shares: { dem: number; rep: number; lib: number; grn: number; other: number };",
    "  /** Presidential votes / registered voters. */",
    "  turnout: number;",
    "  registeredVoters: number;",
    "  registeredSource: string;",
    "  presidentialVotes: number;",
    "}",
    "",
    "export const US_BASELINE_2024: UsBaselineRecord[] = " + json.dumps(records, indent=2) + ";",
    "",
]
TARGET.write_text("\n".join(lines))
fallbacks = [r["id"].upper() for r in records if r["registeredSource"].startswith("game-only")]
print(f"wrote {TARGET} ({len(records)} states); game-only registration fallbacks: {fallbacks}; median turnout {median_turnout:.4f}")
